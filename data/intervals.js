export function getInterval(id) {
  return INTERVALS.find((item) => item.id === id) || INTERVALS[4];
}

export function getIntervalInversion(id) {
  const interval = getInterval(id);
  const inv = getInterval(interval.inversionId);
  return {
    original: interval,
    inverted: inv,
    rule: `${interval.short} (${interval.semitones} пт) ↔ ${inv.short} (${inv.semitones} пт): сумма = 12 полутонов, сумма ступеней = ${interval.steps + inv.steps + 2 === 9 ? "9" : "9 (1+8)"}`,
  };
}
